import { readFile, writeFile, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dramaToManuscript } from "../src/lib/articles/drama-adapter.mjs";

// Read the data module without depending on package.json's module type.
const root = new URL("../", import.meta.url);
const source = await readFile(new URL("src/data/dramas.js", root), "utf8");
const { dramas } = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const records = dramas.map(dramaToManuscript);
if (new Set(records.map(record => record.slug)).size !== records.length) {
  throw new Error("既存記事のIDが重複しています。");
}
for (const record of records) {
  for (const image of [record.metadata.image, ...record.metadata.subImages]) {
    if (!image.startsWith("/pict/") || image.includes("..")) throw new Error(`画像パスを確認してください: ${image}`);
    await access(new URL(`public${image}`, root));
  }
}
const literal = value => "'" + JSON.stringify(value).replaceAll("'", "''") + "'::jsonb";
const payload = literal(records.map(({ publishedAt, ...record }) => ({
  ...record, metadata: { ...record.metadata, originalPublishedAt: publishedAt },
})));
if (payload.includes("$import$")) throw new Error("SQL区切り文字が原稿と重複しています。");
const sql = `-- 08: Existing articles -> private drafts. Run in Supabase SQL Editor.
-- Generated by node scripts/import-static-drafts.mjs; do not edit by hand.
begin;
set local standard_conforming_strings = on;
select pg_advisory_xact_lock(hashtext('commerce-engine-static-import'));
do $import$
declare
  admin_id uuid;
  admin_count integer;
begin
  select count(*) into admin_count from public.article_admins;
  if admin_count <> 1 then
    raise exception 'Exactly one article administrator is required; choose the owner explicitly before importing.';
  end if;
  select user_id into admin_id from public.article_admins;
  insert into public.articles (owner_id, slug, type, content, metadata)
  select admin_id, item->>'slug', item->>'type', item->'content', item->'metadata'
  from jsonb_array_elements(${payload}) as source(item)
  where not exists (
    select 1 from public.articles existing
    where existing.owner_id = admin_id and existing.slug = item->>'slug'
  );
end;
$import$;
commit;
-- The publication table is intentionally unchanged.
select slug, content->>'title' as title, revision
from public.articles
where slug in (${records.map(record => "'" + record.slug.replaceAll("'", "''") + "'").join(", ")})
order by slug;
`;
const destination = new URL("supabase/imports/08-static-drafts.sql", root);
await writeFile(destination, sql);
console.log(`${records.length}件の下書き取り込みSQLを作成しました: ${fileURLToPath(destination)}`);
console.log("DBへの接続・実行はしていません。");
